import { readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

// Evaluate only the repository's literal seed array, never imports or application code.
const source = readFileSync(new URL('../lib/skiller-data.ts', import.meta.url), 'utf8');
const literal = source.match(/const seedSkills = (\[[\s\S]*?\]) as const;/)?.[1];
if (!literal) throw new Error('Skill seed array not found; review extractor before updating catalog.');
const skills = runInNewContext(`(${literal})`, {}, { timeout: 1000 });
if (new Set(skills.map(s => s.id)).size !== skills.length) throw new Error('Duplicate skill IDs');
