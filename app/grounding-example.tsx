/** Teaching example only: rendering or opening it never records an attempt. */
export function GroundingExample({ plannedAction = null }: { plannedAction?: string | null }) {
  return <details className="micro-start-example">
    <summary>Показать пример: заметить и описать то, что вокруг</summary>
    <p><strong>Ситуация:</strong> перед разговором трудно удержать внимание. В этом примере человек смотрит на комнату, чтобы заметить конкретные детали. Не нужно добиваться спокойствия.</p>
    <ol>
      <li><strong>Заметить предметы.</strong><p>«Вижу чашку, окно, книгу, лампу и дверь». Если заметили только один предмет, можно начать с него.</p></li>
      <li><strong>Описать наблюдение.</strong><p>«Чашка белая, на ручке синяя полоска». «Некрасивая чашка» — оценка, а цвет и полоска — наблюдаемые детали. Не нужно спорить с оценкой: можно заметить её и вернуться к детали.</p></li>
      <li><strong>Замечать ощущения и звуки, если это подходит.</strong><p>Например: «Спина касается стула, рукава касаются рук; слышу вентилятор и шаги». Не нужно придумывать ощущения или звуки ради нужного количества. Если внимание к телу неприятно, можно остаться с внешним предметом.</p></li>
      <li><strong>Вернуться к следующему действию.</strong><p>«Теперь посмотрю на записанный вопрос для разговора». Это решение из примера: у Вас может быть другое действие.</p></li>
    </ol>
    <p>Если внимание отвлеклось, можно снова заметить одну деталь. Если состояние ухудшается, остановите практику и отметьте «Стало хуже» в результате.</p>
    <div className="micro-start-personal">
      <strong>Теперь Ваша ситуация</strong>
      {plannedAction
        ? <p>Ваша договорённость: «{plannedAction}». Ориентируйтесь на неё; история с разговором только показывает способ замечать детали.</p>
        : <p>Какой доступный предмет Вы можете заметить сейчас? После практики выберите один безопасный следующий шаг в своей ситуации. Если он непонятен, спросите тренера.</p>}
      <p>Заметить один предмет — сокращённая попытка, а не выполнение всех шагов. Открытие примера ничего не записывает; выполнение и пользу Вы отмечаете отдельно.</p>
    </div>
  </details>;
}
