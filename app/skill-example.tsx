export function SkillExample({ skillId, plannedAction = null }: { skillId: string; plannedAction?: string | null }) {
  if (!Object.hasOwn(examples, skillId)) return null;
  const example = examples[skillId as keyof typeof examples];
  return <details className="micro-start-example">
    <summary>Показать пример: {example.title.toLowerCase()}</summary>
    <p><strong>Ситуация:</strong> {example.situation}</p>
    <ol>{example.steps.map(([title, copy]) => <li key={title}><strong>{title}.</strong><p>{copy}</p></li>)}</ol>
    <p>{example.boundary}</p>
    <div className="micro-start-personal">
      <strong>Теперь Ваша ситуация</strong>
      {plannedAction && <p>Ваша договорённость: «{plannedAction}». История выше — только пример, а не Ваше задание.</p>}
      <p>{example.personal}</p>
      <p>Если шаг непонятен, спросите тренера в разговоре. Можно остановиться или выбрать «Шаг не подходит». Чтение примера не считается попыткой; выполнение и пользу Вы отмечаете отдельно.</p>
    </div>
  </details>;
}
