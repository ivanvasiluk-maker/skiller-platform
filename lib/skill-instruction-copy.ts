/** Adapt only exact known catalog fields; saved and custom wording stays intact. */
export function displaySkillSteps(skillId: string, steps: InstructionStep[]): InstructionStep[] {
  if (!Object.hasOwn(variants, skillId)) return steps;
  const known = variants[skillId];
  return steps.map(step => ({ ...step, title: Object.hasOwn(known, step.title) ? known[step.title] : step.title, copy: Object.hasOwn(known, step.copy) ? known[step.copy] : step.copy }));
}
